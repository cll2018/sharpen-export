def block_range(name):
    """Return (start, end) char offsets of a top-level collection block."""
    m = re.search(r'^  - name: "%s"\n' % re.escape(name), src, re.MULTILINE)
    if not m:
        return None
    start = m.start()
    nxt = re.compile(r'^  - name: "', re.MULTILINE).search(src, m.end())
    return start, (nxt.start() if nxt else len(src))


