def obj_field(name, label, sub_fields, indent):
    pad = " " * indent
    out = pad + '- { label: "%s", name: "%s", widget: "object", collapsed: true,\n' % (label, name)
    out += pad + "    fields: [\n"
    for fname, flabel in sub_fields:
        out += pad + '      { label: "%s", name: "%s", widget: "string" },\n' % (flabel, fname)
    out = out.rstrip(",\n") + ",\n"
    out += pad + "    ] }\n"
    return out


