    block = src[start:end]
    m = re.search(r'^(\s*)- \{ label: "[^"]*", name: "description", widget: "text"',
                  block, re.MULTILINE)
    assert m, "description field not found in products-" + lang
    indent = m.group(1)
    insert_at = end_of_flow_map(block, m.start())
    label = "卡片简介" if lang.startswith("zh") else "Card summary"
    hint = SUMMARY_HINT.get(lang, "Short summary shown on the home & products cards (1-2 sentences).")
